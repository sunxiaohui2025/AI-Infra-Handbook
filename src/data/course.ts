export const chOf = (p: number) => CH.find((c) => c.parts.includes(p))!.n;

/** Infra 快速路线：第一章只读 03、05、06、10、11；第二章跳过 16–20 和第 6 篇。 */
function inFast(id: number, part: number, ch: number) {
  if (ch === 1) return [3, 5, 6, 10, 11].includes(id);
  if (part === 6) return false;
  return !(id >= 16 && id <= 20);
}

export const LECTURES: Lecture[] = RAW.map((s, i) => {
  const f = s.split('|');
  const part = +f[0];
  const id = i + 1;
  const ch = chOf(part);
  return {
    id, part, ch,
    title: f[1].replace(' ⭐', '').replace('（选读）', '').trim(),
    q: f[2], demo: f[3],
    key: f[1].includes('⭐'),
    opt: f[1].includes('（选读）') || part === 6,
    fast: inFast(id, part, ch),
  };
});

export const pad = (n: number) => (n < 10 ? '0' + n : String(n));
export const partLs = (p: number) => LECTURES.filter((l) => l.part === p);
export const chLs = (n: number) => LECTURES.filter((l) => l.ch === n);
export const chName = (c: Chapter) => `第${c.cn}章 ${c.name}`;
export const fastCount = (ls: Lecture[]) => ls.filter((l) => l.fast).length;
export const lecture = (id: number) => LECTURES[id - 1];
